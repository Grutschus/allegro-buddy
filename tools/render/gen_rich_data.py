"""Generate src/render/data.rs and src/render/emoji_data.rs from rich==15.0.0 (+ rich-click boxes).

Run with the reference venv: BAB_RICH_PY=/path/to/python; $BAB_RICH_PY tools/render/gen_rich_data.py
"""

import pathlib

import rich
import rich.box as rbox
from rich._emoji_codes import EMOJI
from rich._palettes import EIGHT_BIT_PALETTE, STANDARD_PALETTE
from rich._spinners import SPINNERS
from rich._unicode_data import load
from rich.color import ANSI_COLOR_NAMES
from rich.default_styles import DEFAULT_STYLES
from rich.style import Style

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = '// @generated by tools/render/gen_rich_data.py from rich==15.0.0; do not edit.\n'


def rs_str(s: str) -> str:
    out = []
    for ch in s:
        if ch in '"\\':
            out.append('\\' + ch)
        elif ch == '\n':
            out.append('\\n')
        elif ord(ch) < 32 or 0x7F <= ord(ch) < 0xA0 or 0xFE00 <= ord(ch) <= 0xFE0F or ch == '\u200d':
            out.append(f'\\u{{{ord(ch):x}}}')
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def main() -> None:
    table = load('latest')
    assert table.unicode_version == '17.0.0'
    lines = [HEADER]
    lines.append(f'pub const UNICODE_VERSION: &str = "{table.unicode_version}";\n')
    lines.append('/// Rich `CellTable.widths`: sorted (start, end, width) ranges.')
    lines.append('pub static CELL_WIDTHS: &[(u32, u32, u8)] = &[')
    for start, end, width in table.widths:
        lines.append(f'    (0x{start:x}, 0x{end:x}, {width}),')
    lines.append('];\n')
    lines.append('/// Rich `CellTable.narrow_to_wide` (sorted).')
    lines.append('pub static NARROW_TO_WIDE: &[char] = &[')
    for ch in sorted(table.narrow_to_wide):
        assert len(ch) == 1
        lines.append(f"    '\\u{{{ord(ch):x}}}',")
    lines.append('];\n')

    lines.append('/// Rich `ANSI_COLOR_NAMES`, sorted by name.')
    lines.append('pub static ANSI_COLOR_NAMES: &[(&str, u8)] = &[')
    for name, number in sorted(ANSI_COLOR_NAMES.items()):
        lines.append(f'    ({rs_str(name)}, {number}),')
    lines.append('];\n')

    for pal_name, pal in (('STANDARD_PALETTE', STANDARD_PALETTE), ('EIGHT_BIT_PALETTE', EIGHT_BIT_PALETTE)):
        colors = pal._colors
        lines.append(f'pub static {pal_name}: [(u8, u8, u8); {len(colors)}] = [')
        for r, g, b in colors:
            lines.append(f'    ({r}, {g}, {b}),')
        lines.append('];\n')

    lines.append('/// Rich `DEFAULT_STYLES` as (name, normalized definition), sorted by name.')
    lines.append('pub static DEFAULT_STYLES: &[(&str, &str)] = &[')
    for name, style in sorted(DEFAULT_STYLES.items()):
        definition = str(style)
        assert Style.parse(definition) == style, (name, definition)
        lines.append(f'    ({rs_str(name)}, {rs_str(definition)}),')
    lines.append('];\n')

    boxes = {name: getattr(rbox, name) for name in dir(rbox) if isinstance(getattr(rbox, name), rbox.Box)}
    try:
        import rich_click.rich_box as rcbox

        for name in ('HORIZONTALS_TOP', 'HORIZONTALS_DOUBLE_TOP'):
            boxes[name] = getattr(rcbox, name)
    except ImportError:
        pass
    lines.append('/// Rich `rich.box` definitions (plus rich-click\'s HORIZONTALS_TOP/HORIZONTALS_DOUBLE_TOP).')
    lines.append('pub static BOXES: &[(&str, &str, bool)] = &[')
    for name, b in sorted(boxes.items()):
        lines.append(f'    ({rs_str(name)}, {rs_str(str(b))}, {str(b.ascii).lower()}),')
    lines.append('];\n')
    lines.append('/// Rich `PLAIN_HEADED_SUBSTITUTIONS`.')
    lines.append('pub static PLAIN_HEADED_SUBSTITUTIONS: &[(&str, &str)] = &[')
    names = {id(b): n for n, b in boxes.items()}
    for src, dst in rbox.PLAIN_HEADED_SUBSTITUTIONS.items():
        lines.append(f'    ({rs_str(names[id(src)])}, {rs_str(names[id(dst)])}),')
    lines.append('];\n')

    dots = SPINNERS['dots']
    lines.append(f'pub const DOTS_INTERVAL_MS: f64 = {float(dots["interval"])};')
    lines.append('pub static DOTS_FRAMES: &[&str] = &[')
    for frame in dots['frames']:
        lines.append(f'    {rs_str(frame)},')
    lines.append('];')
    (ROOT / 'src/render/data.rs').write_text('\n'.join(lines) + '\n')

    emoji = [HEADER, '/// Rich `EMOJI` (name -> emoji), sorted by name.', 'pub static EMOJI: &[(&str, &str)] = &[']
    for name, value in sorted(EMOJI.items()):
        emoji.append(f'    ({rs_str(name)}, {rs_str(value)}),')
    emoji.append('];')
    (ROOT / 'src/render/emoji_data.rs').write_text('\n'.join(emoji) + '\n')
    print('rich', rich.__file__)


if __name__ == '__main__':
    main()
