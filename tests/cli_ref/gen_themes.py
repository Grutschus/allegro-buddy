"""Write src/cli/themes.rs from rich-click 1.9.9's theme tables (COLORS, FORMATS).

    python tests/cli_ref/gen_themes.py   # in a venv with rich-click==1.9.9
"""

from pathlib import Path

from rich_click.rich_click_theme import COLORS, FORMATS

OUT = Path(__file__).resolve().parents[2] / 'src' / 'cli' / 'themes.rs'


def rust_str(s: str) -> str:
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def value(v) -> str:
    if v is None:
        return 'TV::None'
    if isinstance(v, bool):
        return f'TV::Bool({str(v).lower()})'
    if isinstance(v, int):
        return f'TV::Int({v})'
    if isinstance(v, str):
        return f'TV::Str({rust_str(v)})'
    if isinstance(v, tuple):
        return f'TV::Tuple(&[{", ".join(str(i) for i in v)}])'
    if isinstance(v, list):
        return f'TV::List(&[{", ".join(rust_str(i) for i in v)}])'
    raise TypeError(v)


def table(name: str, themes: dict) -> str:
    out = [f'pub static {name}: &[ThemeDef] = &[']
    for key, theme in themes.items():
        cb = theme.post_combine_callback
        cb = f'Some(PostCombine::{"SpacedDelimiters" if "spaced" in cb.__name__ else "NotDimTitle"})' if cb else 'None'
        out.append('    ThemeDef {')
        out.append(f'        name: {rust_str(key)},')
        out.append(f'        callback: {cb},')
        out.append('        styles: &[')
        for k, v in theme.styles.items():
            out.append(f'            ({rust_str(k)}, {value(v)}),')
        out.append('        ],')
        out.append('    },')
    out.append('];')
    return '\n'.join(out)


HEADER = '''//! rich-click 1.9.9 theme tables (`rich_click_theme.COLORS` / `FORMATS`), generated by
//! tests/cli_ref/gen_themes.py. Do not edit by hand.

/// A theme value as written in Python.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum TV {
    None,
    Str(&'static str),
    Bool(bool),
    Int(i64),
    Tuple(&'static [i64]),
    List(&'static [&'static str]),
}

/// `post_combine_callback`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PostCombine {
    /// `_spaced_delimiters_callback`.
    SpacedDelimiters,
    /// `_not_dim_title_callback`.
    NotDimTitle,
}

#[derive(Debug)]
pub struct ThemeDef {
    pub name: &'static str,
    pub callback: Option<PostCombine>,
    pub styles: &'static [(&'static str, TV)],
}
'''

OUT.write_text(HEADER + '\n' + table('COLORS', COLORS) + '\n\n' + table('FORMATS', FORMATS) + '\n')
print(f'wrote {OUT}')
