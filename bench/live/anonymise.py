# per output kind: collect (pass 1) and rewrite (pass 2) through the same walkers

JOB_JSON = {
    'user_name': 'user', 'group_name': 'group', 'account': 'account', 'name': 'job',
    'command': 'path', 'current_working_directory': 'path', 'standard_error': 'path',
    'standard_output': 'path', 'standard_input': 'path', 'mail_user': 'email',
    'comment': 'comment', 'admin_comment': 'comment', 'system_comment': 'comment',
    'wckey': 'comment', 'container': 'path', 'container_id': 'comment',
    'burst_buffer': 'comment', 'extra': 'comment', 'selinux_context': 'comment',
    'submit_line': 'comment', 'user_id': 'uid', 'group_id': 'gid',
}
NODE_JSON = {'owner': 'user', 'comment': 'comment', 'extra': 'comment',
             'reason_set_by_user': 'user', 'mcs_label': 'comment'}
PROPS = {
    'JobName': 'job', 'Account': 'account', 'WorkDir': 'path', 'StdErr': 'path',
    'StdOut': 'path', 'StdIn': 'path', 'Command': 'path', 'MailUser': 'email',
    'Comment': 'comment', 'AdminComment': 'comment', 'SystemComment': 'comment',
    'WCKey': 'comment', 'Container': 'path', 'SubmitLine': 'comment',
    'UserId': 'userid', 'GroupId': 'groupid', 'AllowGroups': 'group_list',
    'DenyGroups': 'group_list', 'AllowAccounts': 'account_list',
    'DenyAccounts': 'account_list', 'Users': 'user_list', 'Groups': 'group_list',
    'Accounts': 'account_list', 'Owner': 'user', 'Reason': 'reason',
}
SQUEUE = {'u': 'user', 'j': 'job', 'a': 'account', 'g': 'group', 'Z': 'path', 'o': 'path',
          'k': 'comment'}
SACCT = {'User': 'user', 'JobName': 'job', 'Account': 'account', 'Group': 'group',
         'StdOut': 'path', 'StdErr': 'path', 'WorkDir': 'path', 'Comment': 'comment'}


class Pass:
    """kind -> value function: collect into Names (rewrite=False) or map (True)."""

    def __init__(self, names: Names, rewrite: bool) -> None:
        self.n, self.rewrite = names, rewrite

    def __call__(self, kind: str, value):
        n = self.n
        if not self.rewrite:
            if kind in ('user', 'group', 'account', 'job'):
                n.add(kind, value)
            elif kind == 'userid':
                n.add('user', str(value).split('(')[0])
            elif kind == 'groupid':
                n.add('group', str(value).split('(')[0])
            elif kind.endswith('_list'):
                for x in str(value).split(','):
                    n.add(kind[:-5], x)
            elif kind == 'email' and value:
                n.emails.add(value)
                n.add('user', value.split('@')[0])
            elif kind == 'path' and value:
                n.raw_paths.add(value)
            return value
        if kind in ('userid', 'groupid'):
            m = re.fullmatch(r'(.*?)\((\d+)\)', str(value))
            if not m:
                return value
            fn = (n.user, n.uid) if kind == 'userid' else (n.group, n.gid)
            return f'{fn[0](m.group(1))}({fn[1](m.group(2))})'
        if kind == 'reason':
            return value
        return getattr(n, kind)(value)

    def text(self, value: str) -> str:
        return textual(self.n, value)


def leaves(obj, fn):
    if isinstance(obj, dict):
        return {k: leaves(v, fn) for k, v in obj.items()}
    if isinstance(obj, list):
        return [leaves(v, fn) for v in obj]
    return fn(obj) if isinstance(obj, str) else obj


def walk_json(text: str, f: Pass, argv: list[str]) -> str:
    try:
        data = json.loads(text)
    except ValueError:
        return text
    if not f.rewrite and argv[-1] == 'nodes':
        f.n.vocab.update(re.findall(r'[\w.-]+', text))
    meta = data.get('meta', {}).get('client', {})
    if 'user' in meta:
        meta['user'] = f('user', meta['user'])
    if 'group' in meta:
        meta['group'] = f('group', meta['group'])
    for job in data.get('jobs', []):
        for key, kind in JOB_JSON.items():
            if key in job and isinstance(job[key], (str, int)):
                job[key] = f(kind, job[key])
                if kind in ('uid', 'gid') and not f.rewrite:
                    pass
        if f.rewrite:
            for key in ('user_id', 'group_id'):
                if isinstance(job.get(key), str):
                    job[key] = int(job[key])
    for node in data.get('nodes', []):
        for key, kind in NODE_JSON.items():
            if isinstance(node.get(key), str):
                node[key] = f(kind, node[key])
    if f.rewrite:
        data = leaves(data, f.text)
    return json.dumps(data, indent=2, ensure_ascii=False) + '\n'


def walk_props(text: str, f: Pass) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        body = line.rstrip('\n')
        pieces, last = [], 0
        for m in PROP_RE.finditer(body):
            key, value = m.group(1), m.group(2)
            kind = PROPS.get(key)
            new = str(f(kind, value)) if kind else value
            if f.rewrite:
                new = f.text(new)
            if new != value:
                pieces.append(body[last:m.start(2)])
                pieces.append(new)
                last = m.end(2)
        pieces.append(body[last:])
        out.append(''.join(pieces) + line[len(body):])
    return ''.join(out)


def squeue_format(argv: list[str]) -> list[str] | None:
    for i, a in enumerate(argv):
        if a.startswith('--format='):
            fmt = a.split('=', 1)[1]
        elif a in ('-o', '--format') and i + 1 < len(argv):
            fmt = argv[i + 1]
        else:
            continue
        return [re.sub(r'^%[.\d]*', '', part)[:1] for part in fmt.split('|')]
    return None


def walk_rows(text: str, columns: list[str], kinds: dict[str, str], f: Pass) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        body = line.rstrip('\n')
        parts = body.split('|')
        if len(parts) == len(columns):
            parts = [str(f(kinds[c], p)) if c in kinds else p for c, p in zip(columns, parts)]
        if f.rewrite:
            parts = [f.text(p) for p in parts]
        out.append('|'.join(parts) + line[len(body):])
    return ''.join(out)


def map_argv(argv: list[str], f: Pass) -> list[str]:
    out = []
    for i, a in enumerate(argv):
        if a.startswith('--user='):
            a = '--user=' + str(f('user', a[7:]))
        elif i > 0 and argv[i - 1] in ('-u', '--user'):
            a = str(f('user', a))
        elif i > 0 and argv[i - 1] == 'user' and argv[0] == 'sacctmgr':
            a = str(f('user', a))
        out.append(a)
    return out


def walk_call(call: dict, f: Pass) -> dict:
    argv = call['argv']
    name, out = argv[0], call.get('stdout', '')
    if name == 'scontrol' and '--json' in argv:
        out = walk_json(out, f, argv)
    elif name == 'scontrol' and argv[1:] == ['show', 'config']:
        if f.rewrite:
            out = ''.join(
                line for line in out.splitlines(keepends=True)
                if line.startswith('Configuration data') or line.split('=')[0].strip() in CONFIG_KEYS
            )
    elif name == 'scontrol':
        if not f.rewrite and argv[-1] == 'partition':
            f.n.vocab.update(re.findall(r'[\w.-]+', re.sub(r'(Allow|Deny)\w+=\S+', '', out)))
        out = walk_props(out, f)
    elif name == 'squeue':
        cols = squeue_format(argv)
        if cols:
            out = walk_rows(out, cols, SQUEUE, f)
    elif name == 'sacct':
        fmt = next((a.split('=', 1)[1] for a in argv if a.startswith('--format=')), '')
        if fmt:
            out = walk_rows(out, fmt.split(','), SACCT, f)
    elif name == 'sacctmgr':
        fmt = next((a.split('=', 1)[1] for a in argv if a.startswith('format=')), '')
        kinds = {'DefaultAccount': 'account', 'Account': 'account', 'User': 'user'}
        if fmt:
            out = walk_rows(out, fmt.split(','), kinds, f)
    new = dict(call)
    new['argv'] = map_argv(argv, f)
    new['stdout'] = out
    return new


