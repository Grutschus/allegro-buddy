#!/usr/bin/env python3
"""Anonymise recorded datasets (record.py) with consistent pseudonyms, for committing.

    anonymise.py OUT NAME=DATASET [NAME=DATASET ...]

Writes OUT/NAME/{calls.jsonl.gz,runs.jsonl,meta.json} for every dataset and
OUT/pseudonyms.json (counts only, never the real names). One mapping is shared by all
datasets (the same real user is the same pseudonym everywhere):

  users      userNN (the recording user is user00), uid -> 20000+n
  groups     groupNN, gid -> 30000+n           (partition AllowGroups and the
                                                recorded `id -Gn` stay consistent)
  accounts   acctNN
  job names  same-length pseudonyms (jobNNN + filler), so tables wrap/cut the same way
  paths      every component but a few generic ones (home, data, scratch, ...) -> dNNN,
             user components -> the user's pseudonym, extensions kept
  emails     <user>@example.org;  comments -> "comment"
Node names, partitions, GPU types, TRES, times and job ids stay. `scontrol show config`
keeps only ClusterName and a few scheduler keys. System accounts (root, slurm, adm)
stay. A final textual pass replaces any leftover real name, and `check()` proves that
no real user/group/account/job name, email or home path is left (exit 1 otherwise).

The reference outputs in runs.jsonl are regenerated by replaying the anonymised calls
through the Python reference (compat venv, --no-outputs to skip).
"""

from __future__ import annotations

import gzip
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
KEEP_NAMES = {'root', 'slurm', 'adm', 'ALL', '(null)', 'N/A', 'None', '', 'nobody'}
KEEP_DIRS = {'', 'home', 'data', 'scratch', 'storage', 'dev', 'null', 'tmp', 'work',
             'results', 'run', 'logs', 'log', 'out', 'srv', 'public', 'users', 'projects'}
CONFIG_KEYS = {'ClusterName', 'SLURM_VERSION', 'SelectType', 'SelectTypeParameters',
               'PriorityType', 'SchedulerType', 'GresTypes', 'MaxArraySize', 'PreemptMode'}
FILLER = 'abcdefghijklmnopqrstuvwxyz'
PROP_RE = re.compile(r'(\S+?)=(.*?)(?=\s+\S+=|$)')


class Names:
    def __init__(self) -> None:
        self.users: dict[str, str] = {}
        self.groups: dict[str, str] = {}
        self.accounts: dict[str, str] = {}
        self.jobs: dict[str, str] = {}
        self.dirs: dict[str, str] = {}
        self.uids: dict[str, str] = {}
        self.gids: dict[str, str] = {}
        self.emails: set[str] = set()
        self.raw_users: set[str] = set()
        self.raw_groups: set[str] = set()
        self.raw_accounts: set[str] = set()
        self.raw_jobs: set[str] = set()
        self.raw_paths: set[str] = set()
        self.pattern = None
        self.table: dict[str, str] = {}
        self.vocab: set[str] = {
            'RUNNING', 'PENDING', 'COMPLETED', 'FAILED', 'CANCELLED', 'TIMEOUT', 'bash',
            'sh', 'python', 'test', 'job', 'run', 'interactive', 'gpu', 'cpu', 'none',
        }

    # collection -----------------------------------------------------------------
    def add(self, kind: str, value: str) -> None:
        value = (value or '').strip()
        if value in KEEP_NAMES:
            return
        getattr(self, 'raw_' + kind + 's').add(value)

    def finish(self, me: str) -> None:
        self.raw_users.discard(me)
        self.users[me] = 'user00'
        for i, name in enumerate(sorted(self.raw_users), 1):
            self.users[name] = f'user{i:02d}'
        self.raw_users.add(me)
        for i, name in enumerate(sorted(self.raw_groups), 1):
            self.groups[name] = f'group{i:02d}'
        for i, name in enumerate(sorted(self.raw_accounts), 1):
            self.accounts[name] = f'acct{i:02d}'
        for i, name in enumerate(sorted(self.raw_jobs), 1):
            core = f'job{i:03d}'
            self.jobs[name] = core if len(name) <= len(core) else (
                core + '_' + FILLER * 4)[:len(name)]

    # mapping --------------------------------------------------------------------
    def user(self, v: str) -> str:
        return self.users.get(v, v)

    def group(self, v: str) -> str:
        return self.groups.get(v, v)

    def account(self, v: str) -> str:
        return self.accounts.get(v, v)

    def job(self, v: str) -> str:
        return self.jobs.get(v, v)

    def uid(self, v) -> str:
        return self.uids.setdefault(str(v), str(20000 + len(self.uids)))

    def gid(self, v) -> str:
        return self.gids.setdefault(str(v), str(30000 + len(self.gids)))

    def email(self, v: str) -> str:
        if not v or v in KEEP_NAMES:
            return v
        local = v.split('@')[0]
        return f'{self.user(local) if local in self.users else "someone"}@example.org'

    def path(self, v: str) -> str:
        if not v or v in KEEP_NAMES or not v.startswith('/'):
            return self.dir(v) if v and v not in KEEP_NAMES else v
        return '/'.join(self.dir(part) for part in v.split('/'))

    def dir(self, part: str) -> str:
        if part in KEEP_DIRS or re.fullmatch(r'slurm-[%\dAaj_]+\.(out|err)', part):
            return part
        if part in self.users:
            return self.users[part]
        stem, dot, ext = part.partition('.')
        ext = dot + ext if re.fullmatch(r'[A-Za-z0-9%]{1,4}(\.[A-Za-z0-9%]{1,4})?', ext) else ''
        if part not in self.dirs:
            self.dirs[part] = f'd{len(self.dirs):03d}'
        return self.dirs[part] + ext

    def comment(self, v: str) -> str:
        return v if v in KEEP_NAMES else 'comment'

    def user_list(self, v: str) -> str:
        return ','.join(self.user(x) for x in v.split(','))

    def group_list(self, v: str) -> str:
        return ','.join(self.group(x) for x in v.split(','))

    def account_list(self, v: str) -> str:
        return ','.join(self.account(x) for x in v.split(','))


