def load(dataset: Path) -> tuple[list[dict], list[dict], dict]:
    calls = [json.loads(x) for x in (dataset / 'calls.jsonl').read_text().splitlines() if x]
    runs = [json.loads(x) for x in (dataset / 'runs.jsonl').read_text().splitlines() if x]
    return calls, runs, json.loads((dataset / 'meta.json').read_text())


def textual(names: Names, text: str) -> str:
    """Last line of defence: any real name left anywhere (word-bounded)."""
    if names.pattern is None:
        table = {
            **{k: v for k, v in names.jobs.items() if k not in names.vocab},
            **names.users, **names.groups, **names.accounts,
        }
        table = {k: v for k, v in table.items() if len(k) >= 3}
        names.table = table
        alternation = '|'.join(re.escape(k) for k in sorted(table, key=len, reverse=True))
        names.pattern = re.compile(rf'(?<![\w.-])(?:{alternation})(?![\w-])')
    if not text:
        return text
    text = names.pattern.sub(lambda m: names.table[m.group(0)], text)
    if '@' in text:
        for email in names.emails:
            text = text.replace(email, names.email(email))
    return re.sub(r'[\w.-]*fu-berlin\.de', 'example.org', text) if 'fu-berlin' in text else text


def check(names: Names, root: Path) -> list[str]:
    """Every real user/group/account/email/home path/distinctive job name: 0 hits."""
    blob = ''
    for path in sorted(root.rglob('*')):
        if path.is_file():
            data = path.read_bytes()
            blob += (gzip.decompress(data) if path.suffix == '.gz' else data).decode()
    problems = []
    for kind, values in (('user', names.raw_users), ('group', names.raw_groups),
                         ('account', names.raw_accounts)):
        for v in values:
            if len(v) >= 3 and re.search(rf'(?<![\w-]){re.escape(v)}(?![\w-])', blob):
                problems.append(f'{kind} {v!r}')
    for v in names.raw_jobs:
        if len(v) >= 4 and v not in names.vocab and re.search(rf'(?<![\w.-]){re.escape(v)}(?![\w-])', blob):
            problems.append(f'job name {v!r}')
    for v in names.emails:
        if v in blob:
            problems.append(f'email {v!r}')
    for v in names.raw_paths:
        if len(v) > 5 and v != '/dev/null' and v in blob:
            problems.append(f'path {v!r}')
    for pattern in (r'fu-berlin', r'@(?!example\.org)[\w-]+\.[a-z]{2,}', r'/home/(?!user\d\d|d\d{3})\w+'):
        for m in set(re.findall(pattern, blob)):
            problems.append(f'pattern {m!r}')
    return problems


def main() -> int:
    args = sys.argv[1:]
    outputs = '--no-outputs' not in args
    args = [a for a in args if a != '--no-outputs']
    if len(args) < 2:
        sys.exit(__doc__)
    out = Path(args[0]).resolve()
    sets = {kv.split('=', 1)[0]: load(Path(kv.split('=', 1)[1])) for kv in args[1:]}
    names = Names()
    collect = Pass(names, rewrite=False)
    me = None
    for calls, runs, meta in sets.values():
        me = meta.get('real_user') or meta['user']
        names.add('user', meta['user'])
        for g in [*meta['groups'], *meta.get('python_groups', [])]:
            names.add('group', g)
        for key in ('other_user', 'other_user2'):
            names.add('user', meta.get('placeholders', {}).get(key, ''))
        for call in calls:
            walk_call(call, collect)
            map_argv(call['argv'], collect)
        for run in runs:
            map_argv(run['args'], collect)
    names.finish(me)
    rewrite = Pass(names, rewrite=True)

    for set_name, (calls, runs, meta) in sets.items():
        target = out / set_name
        target.mkdir(parents=True, exist_ok=True)
        lines = []
        for call in calls:
            new = walk_call(call, rewrite)
            if new['argv'][:3] == ['scontrol', 'show', 'config']:
                new['stdout'] = textual(names, new['stdout'])
            new['stderr'] = textual(names, new.get('stderr', ''))
            lines.append(json.dumps(new, ensure_ascii=False))
        data = ('\n'.join(lines) + '\n').encode()
        (target / 'calls.jsonl.gz').write_bytes(gzip.compress(data, 9, mtime=0))
        new_meta = dict(meta)
        new_meta['user'] = names.user(meta['user'])
        new_meta['real_user'] = names.user(meta.get('real_user', meta['user']))
        new_meta['groups'] = [names.group(g) for g in meta['groups']]
        new_meta['python_groups'] = sorted(names.group(g) for g in meta.get('python_groups', []))
        new_meta['placeholders'] = {
            k: names.user(v) if 'user' in k else v for k, v in meta['placeholders'].items()
        }
        new_meta['versions'] = {**meta['versions'], 'reference': meta['versions']['reference']}
        new_meta['anonymised'] = True
        (target / 'meta.json').write_text(json.dumps(new_meta, indent=2) + '\n')
        new_runs = []
        for run in runs:
            r = {k: run[k] for k in ('id', 'args', 'now', 'columns', 'exit', 't0', 't1')}
            r['args'] = map_argv(run['args'], rewrite)
            r['args'] = [names.user(a) if a in names.users else a for a in r['args']]
            new_runs.append(r)
        if outputs:
            regenerate(target, new_runs, new_meta)
        (target / 'runs.jsonl').write_text(
            ''.join(json.dumps(r, ensure_ascii=False) + '\n' for r in new_runs))

    (out / 'pseudonyms.json').write_text(json.dumps({
        'users': len(names.users), 'groups': len(names.groups),
        'accounts': len(names.accounts), 'job_names': len(names.jobs),
        'path_components': len(names.dirs), 'uids': len(names.uids), 'gids': len(names.gids),
    }, indent=2) + '\n')
    problems = check(names, out)
    for p in problems:
        print('LEAK', p, file=sys.stderr)
    print(f'anonymised {len(sets)} datasets into {out}: {len(problems)} leaks', file=sys.stderr)
    return 1 if problems else 0


def regenerate(target: Path, runs: list[dict], meta: dict) -> None:
    """stdout/stderr/exit of the reference on the anonymised replay (recorded columns)."""
    sys.path.insert(0, str(HERE.parent / 'replay'))
    import build as replay_build
    import parity

    work = target.parent / '.regen'
    (target / 'runs.jsonl').write_text(''.join(json.dumps(r) + '\n' for r in runs))
    replay_build.build(target, work / 'replay')
    ref = [parity.default_python(), str(parity.REPO / 'compat/reference.py'), 'run']
    for run in runs:
        case = {**run, 'columns': int(run['columns']), 'color': 0, 'cache': 'warm'}
        result = parity.run_case(ref, case, work / 'replay', meta, work / 'w')
        run['exit'] = result['exit']
        run['stdout'] = result['stdout'].replace(str(work / 'w'), '@WORK@')
        run['stderr'] = result['stderr'].replace(str(work / 'w'), '@WORK@')
        run['output_of'] = 'compat reference (renamed bab) on this anonymised replay'
    import shutil

    shutil.rmtree(work)


if __name__ == '__main__':
    sys.exit(main())
